function elapsedOf(t) {
  return t.accumMs + (t.running && t.startedAt ? Date.now() - t.startedAt : 0);
}

function loadTimers() {
  try {
    const raw = localStorage.getItem(TIMERS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.map((t) => ({
      id: t.id || "t" + timerUid++,
      type:
        t.type === "pomodoro"
          ? "pomodoro"
          : t.type === "stopwatch"
            ? "stopwatch"
            : "timer",
      durationMs: Number(t.durationMs) || 0,
      workMs: Number(t.workMs) || 0,
      breakMs: Number(t.breakMs) || 0,
      phase: t.phase || "work",
      cycle: Number(t.cycle) || 1,
      accumMs: Number(t.accumMs) || 0,
      startedAt: t.startedAt || null,
      running: !!t.running,
      done: !!t.done,
      chimed: true,
    }));
  } catch {
    return [];
  }
}

function saveTimers() {
  try {
    localStorage.setItem(TIMERS_KEY, JSON.stringify(timers));
  } catch {}
}

function ensureAudio() {
  try {
    if (!audioCtx) {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (AC) audioCtx = new AC();
    }
    if (audioCtx && audioCtx.state === "suspended") audioCtx.resume();
  } catch {}
}

function playChime() {
  if (!audioCtx) return;
  try {
    const now = audioCtx.currentTime;
    const notes = [523.25, 659.25, 783.99];
    notes.forEach((freq, i) => {
      const osc = audioCtx.createOscillator();
      const gain = audioCtx.createGain();
      osc.type = "sine";
      osc.frequency.value = freq;
      const start = now + i * 0.14;
      gain.gain.setValueAtTime(0.0001, start);
      gain.gain.linearRampToValueAtTime(0.15, start + 0.03);
      gain.gain.exponentialRampToValueAtTime(0.0001, start + 0.5);
      osc.connect(gain);
      gain.connect(audioCtx.destination);
      osc.start(start);
      osc.stop(start + 0.55);
    });
  } catch {}
}

function formatClock(ms, ceilSec) {
  if (ms < 0) ms = 0;
  const totalSec = ceilSec ? Math.ceil(ms / 1000) : Math.floor(ms / 1000);
  const h = Math.floor(totalSec / 3600);
  const m = Math.floor((totalSec % 3600) / 60);
  const s = totalSec % 60;
  const pad = (n) => String(n).padStart(2, "0");
  if (h > 0) return h + ":" + pad(m) + ":" + pad(s);
  return m + ":" + pad(s);
}

