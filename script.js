let uid = 1;
let boardUid = 1;

function generateBoardId() {
  return "b" + boardUid++;
}

function getCleanText(html) {
  if (!html) return "";
  const doc = new DOMParser().parseFromString(html, "text/html");
  return doc.body.textContent || "";
}
function esc(c) {
  return c.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
function titleFromBody(body) {
  return getCleanText(body).trim().split("\n")[0] || "untitled";
}

const boardEl = document.getElementById("board");

function createDefaultState() {
  return {
    boards: [
      {
        id: generateBoardId(),
        name: "My Board",
        columns: JSON.parse(JSON.stringify(COLUMNS)),
      },
    ],
    activeBoardId: null,
  };
}

function validateColumns(cols) {
  return cols.map((col, i) => ({
    title: col.title || COLUMNS[i]?.title || "untitled",
    cards: Array.isArray(col.cards)
      ? col.cards.map((item) => {
          if (typeof item === "string")
            return { body: item, color: "", tags: [] };
          return {
            body: item?.body || "",
            color: item?.color || "",
            tags: Array.isArray(item?.tags) ? item.tags : [],
          };
        })
      : [],
  }));
}

function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return createDefaultState();
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed)) {
      const def = createDefaultState();
      def.boards[0].columns = validateColumns(parsed);
      def.activeBoardId = def.boards[0].id;
      return def;
    }
    if (parsed && typeof parsed === "object" && Array.isArray(parsed.boards)) {
      parsed.boards = parsed.boards.map((b) => ({
        ...b,
        columns: validateColumns(b.columns || []),
      }));
      if (!parsed.boards.some((b) => b.id === parsed.activeBoardId)) {
        parsed.activeBoardId = parsed.boards[0]?.id || null;
      }
      const maxUid = parsed.boards.reduce(
        (m, b) =>
          Math.max(m, parseInt(String(b.id).replace(/\D/g, ""), 10) || 0),
        0,
      );
      boardUid = maxUid + 1;
      return parsed;
    }
    return createDefaultState();
  } catch {
    return createDefaultState();
  }
}

function activeBoard() {
  return state.boards.find((b) => b.id === state.activeBoardId);
}

function activeBoardColumns() {
  const b = activeBoard();
  return b ? b.columns : [];
}

let state = loadState();
if (!state.activeBoardId && state.boards.length > 0) {
  state.activeBoardId = state.boards[0].id;
}

const MAX_HISTORY = 50;
let undoStack = [];
let redoStack = [];

function pushSnapshot() {
  undoStack.push(JSON.parse(JSON.stringify(state)));
  if (undoStack.length > MAX_HISTORY) undoStack.shift();
  redoStack = [];
}

function undo() {
  if (undoStack.length === 0) return;
  redoStack.push(JSON.parse(JSON.stringify(state)));
  state = undoStack.pop();
  saveState();
  if (activeCard) {
    activeCard = null;
    overlay.classList.remove("open");
  }
  closePalette();
  buildBoard();
}

function redo() {
  if (redoStack.length === 0) return;
  undoStack.push(JSON.parse(JSON.stringify(state)));
  state = redoStack.pop();
  saveState();
  if (activeCard) {
    activeCard = null;
    overlay.classList.remove("open");
  }
  closePalette();
  buildBoard();
}

pushSnapshot();

function saveState() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch {}
}

function exportBoard() {
  syncStateFromDOM();
  const board = activeBoard();
  if (!board) return;
  const json = JSON.stringify(board.columns, null, 2);
  const blob = new Blob([json], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = (board.name || "board") + ".json";
  a.click();
  URL.revokeObjectURL(url);
}

function importBoard(file) {
  if (!file) return;
  const reader = new FileReader();
  reader.onload = (e) => {
    try {
      const parsed = JSON.parse(e.target.result);
      if (!Array.isArray(parsed)) throw new Error();
      const board = activeBoard();
      if (!board) throw new Error();
      const validated = validateColumns(parsed);
      if (activeCard) closeEditor();
      pushSnapshot();
      board.columns = validated;
      saveState();
      buildBoard();
    } catch {
      alert("Invalid board file.");
    }
  };
  reader.readAsText(file);
  fileInput.value = "";
}

function syncStateFromDOM() {
  const board = activeBoard();
  if (!board) return;
  board.columns = [...boardEl.querySelectorAll(".column")].map((col) => ({
    title: col.querySelector(".title")?.textContent || "untitled",
    cards: [...col.querySelectorAll(".card:not(.card-removing)")].map(
      (card) => ({
        body: card.dataset.body || "",
        color: card.dataset.color || "",
        tags: JSON.parse(card.dataset.tags || "[]"),
      }),
    ),
  }));
}

function makeCard(input) {
  const body = typeof input === "string" ? input : input?.body || "";
  const color = typeof input === "string" ? "" : input?.color || "";
  const tags =
    typeof input === "string"
      ? []
      : Array.isArray(input?.tags)
        ? input.tags
        : [];
  const card = document.createElement("div");
  card.className = "card";
  card.draggable = true;
  card.dataset.id = "c" + uid++;
  card.dataset.body = body || "";
  card.dataset.color = color;
  card.dataset.tags = JSON.stringify(tags);

  const title = document.createElement("span");
  title.className = "card-title";
  card.appendChild(title);

  const x = document.createElement("button");
  x.className = "card-x";
  x.innerHTML = ICON_X;
  card.appendChild(x);

  refreshCard(card);

  card.addEventListener("click", () => openEditor(card));
  x.addEventListener("click", (e) => {
    e.stopPropagation();
    const add = card.closest(".column").querySelector(".add-card");

    const movers = [];
    let sib = card.nextElementSibling;
    while (sib) {
      if (sib.classList.contains("card")) movers.push(sib);
      sib = sib.nextElementSibling;
    }
    movers.push(add);
    const fromTops = movers.map((el) => el.getBoundingClientRect().top);

    const offTop = card.offsetTop;
    const w = card.offsetWidth;
    card.style.position = "absolute";
    card.style.top = offTop + "px";
    card.style.left = "0";
    card.style.width = w + "px";
    card.style.margin = "0";
    card.classList.add("card-removing");

    movers.forEach((el, i) => animateAddButton(el, fromTops[i]));

    pushSnapshot();
    syncStateFromDOM();
    saveState();

    card.addEventListener(
      "animationend",
      () => {
        card.remove();
      },
      { once: true },
    );
  });

  card.addEventListener("dragstart", () => {
    dragged = card;
    card.classList.add("dragging");
  });
  card.addEventListener("dragend", () => {
    card.classList.remove("dragging");
    dragged = null;
    document
      .querySelectorAll(".cards.drag-over")
      .forEach((c) => c.classList.remove("drag-over"));
  });

  return card;
}

function refreshCard(card) {
  const body = card.dataset.body;
  const clean = titleFromBody(body);
  card.querySelector(".card-title").textContent = clean;
  card.classList.toggle("empty", !getCleanText(body).trim());

  let tagsContainer = card.querySelector(".card-tags");
  if (!tagsContainer) {
    tagsContainer = document.createElement("div");
    tagsContainer.className = "card-tags";
    card.insertBefore(tagsContainer, card.querySelector(".card-title"));
  }
  const tags = JSON.parse(card.dataset.tags || "[]");
  tagsContainer.innerHTML = tags
    .map((t) => `<span class="tag-chip">${esc(t)}</span>`)
    .join("");
  tagsContainer.style.display = tags.length ? "flex" : "none";

  if (card.dataset.color) {
    card.style.setProperty("--card-bg", card.dataset.color);
    card.style.setProperty("--card-fg", "#1a1a1a");
  } else {
    card.style.removeProperty("--card-bg");
    card.style.removeProperty("--card-fg");
  }
}

function buildBoard() {
  boardEl.innerHTML = "";
  const board = activeBoard();
  if (!board) return;

  const titleEl = document.createElement("div");
  titleEl.className = "board-title";
  titleEl.textContent = board.name;
  titleEl.addEventListener("click", (e) => {
    e.stopPropagation();
    titleEl.contentEditable = "true";
    titleEl.classList.add("editing");
    titleEl.focus();
    const range = document.createRange();
    range.selectNodeContents(titleEl);
    const sel = window.getSelection();
    sel.removeAllRanges();
    sel.addRange(range);
  });
  titleEl.addEventListener("blur", () => {
    titleEl.contentEditable = "false";
    titleEl.classList.remove("editing");
    renameBoard(board.id, titleEl.textContent);
  });
  titleEl.addEventListener("keydown", (e) => {
    if (e.key === "Enter") {
      e.preventDefault();
      titleEl.blur();
    }
    if (e.key === "Escape") {
      e.preventDefault();
      titleEl.textContent = board.name;
      titleEl.blur();
    }
  });
  boardEl.appendChild(titleEl);

  const boardColumnsEl = document.createElement("div");
  boardColumnsEl.className = "board-columns no-scrollbar";

  board.columns.forEach((col, colIndex) => {
    const column = document.createElement("div");
    column.className = "column";
    const header = document.createElement("div");
    header.className = "column-header";

    const title = document.createElement("span");
    title.className = "title";
    title.textContent = col.title;
    header.appendChild(title);

    column.appendChild(header);

    title.addEventListener("click", (e) => {
      e.stopPropagation();
      title.contentEditable = "true";
      title.classList.add("editing");
      title.focus();
      const range = document.createRange();
      range.selectNodeContents(title);
      const sel = window.getSelection();
      sel.removeAllRanges();
      sel.addRange(range);
    });
    title.addEventListener("blur", () => {
      title.contentEditable = "false";
      title.classList.remove("editing");
      const newTitle = title.textContent.trim() || "untitled";
      title.textContent = newTitle;
      pushSnapshot();
      board.columns[colIndex].title = newTitle;
      saveState();
    });
    title.addEventListener("keydown", (e) => {
      if (e.key === "Enter") {
        e.preventDefault();
        title.blur();
      }
    });

    const cards = document.createElement("div");
    cards.className = "cards no-scrollbar";
    column.appendChild(cards);

    col.cards.forEach((text) => cards.appendChild(makeCard(text)));

    const add = document.createElement("button");
    add.className = "add-card";
    add.innerHTML = ICON_PLUS + "<span>add card</span>";
    add.addEventListener("click", () => {
      const addTop = add.getBoundingClientRect().top;
      const c = makeCard({ body: "", color: "", tags: [] });
      c.classList.add("card-enter");
      cards.appendChild(c);

      pushSnapshot();
      board.columns[colIndex].cards.push({ body: "", color: "", tags: [] });
      saveState();
      animateAddButton(add, addTop);

      setTimeout(() => {
        c.classList.remove("card-enter");
      }, 520);
    });
    column.appendChild(add);

    cards.addEventListener("dragover", (e) => {
      e.preventDefault();
      cards.classList.add("drag-over");
      if (!dragged) return;
      const after = afterElement(cards, e.clientY);
      if (after == null) cards.appendChild(dragged);
      else cards.insertBefore(dragged, after);
    });
    cards.addEventListener("dragleave", (e) => {
      if (!cards.contains(e.relatedTarget)) cards.classList.remove("drag-over");
    });
    cards.addEventListener("drop", (e) => {
      e.preventDefault();
      cards.classList.remove("drag-over");
      pushSnapshot();
      syncStateFromDOM();
      saveState();
    });

    boardColumnsEl.appendChild(column);
  });

  boardEl.appendChild(boardColumnsEl);
}

function afterElement(container, y) {
  const els = [...container.querySelectorAll(".card:not(.dragging)")];
  let closest = { offset: -Infinity, el: null };
  for (const el of els) {
    const box = el.getBoundingClientRect();
    const offset = y - box.top - box.height / 2;
    if (offset < 0 && offset > closest.offset) closest = { offset, el };
  }
  return closest.el;
}

function animateAddButton(add, fromTop) {
  const toTop = add.getBoundingClientRect().top;
  const delta = fromTop - toTop;
  if (!delta) return;
  const easing =
    getComputedStyle(document.documentElement)
      .getPropertyValue("--curve")
      .trim() || "cubic-bezier(0.16, 1, 0.3, 1)";
  add.getAnimations().forEach((anim) => anim.cancel());
  add.animate(
    [{ transform: `translateY(${delta}px)` }, { transform: "translateY(0)" }],
    { duration: 520, easing },
  );
}

function addCardToColumn(colIndex, body) {
  const columns = boardEl.querySelectorAll(".column");
  const column = columns[colIndex];
  const board = activeBoard();
  if (!column || !board || !board.columns[colIndex]) return;
  const cards = column.querySelector(".cards");
  const add = column.querySelector(".add-card");
  const addTop = add.getBoundingClientRect().top;

  const c = makeCard({ body: body || "", color: "", tags: [] });
  c.classList.add("card-enter");
  cards.appendChild(c);

  pushSnapshot();
  board.columns[colIndex].cards.push({ body: body || "", color: "", tags: [] });
  saveState();
  animateAddButton(add, addTop);

  setTimeout(() => c.classList.remove("card-enter"), 520);
}

function createBoard(name) {
  const board = {
    id: generateBoardId(),
    name: name || "Untitled",
    columns: JSON.parse(JSON.stringify(COLUMNS)),
  };
  pushSnapshot();
  state.boards.push(board);
  saveState();
  return board;
}

function renameBoard(boardId, name) {
  const board = state.boards.find((b) => b.id === boardId);
  if (!board) return;
  pushSnapshot();
  board.name = name.trim() || "Untitled";
  saveState();
}

function switchBoard(boardId) {
  const board = state.boards.find((b) => b.id === boardId);
  if (!board || board.id === state.activeBoardId) return;
  if (activeCard) closeEditor();
  pushSnapshot();
  state.activeBoardId = boardId;
  saveState();
  buildBoard();
}

function deleteBoard(boardId) {
  if (state.boards.length <= 1) return;
  const idx = state.boards.findIndex((b) => b.id === boardId);
  if (idx === -1) return;
  pushSnapshot();
  state.boards.splice(idx, 1);
  if (state.activeBoardId === boardId) {
    state.activeBoardId =
      state.boards[Math.min(idx, state.boards.length - 1)].id;
  }
  if (activeCard) closeEditor();
  saveState();
  buildBoard();
}

function animateGridItems(grid, beforeFn) {
  const items = [...grid.children];
  const oldRects = items.map((el) => el.getBoundingClientRect());
  beforeFn();
  items.forEach((el, i) => {
    if (!grid.contains(el)) return;
    const newRect = el.getBoundingClientRect();
    const dx = oldRects[i].left - newRect.left;
    const dy = oldRects[i].top - newRect.top;
    if (dx || dy) {
      el.animate(
        [
          { transform: `translate(${dx}px, ${dy}px)` },
          { transform: "translate(0, 0)" },
        ],
        { duration: 450, easing: "cubic-bezier(0.16, 1, 0.3, 1)" },
      );
    }
  });
}

