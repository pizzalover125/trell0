function resumeTimer(t) {
  if (t.running || t.done) return;
  t.startedAt = Date.now();
  t.running = true;
  updateChip(t);
  saveTimers();
  startTick();
}

function restartTimer(t) {
  t.accumMs = 0;
  t.startedAt = Date.now();
  t.running = true;
  t.done = false;
  t.chimed = false;
  const refs = chipEls[t.id];
  if (refs) refs.chip.classList.remove("done");
  updateChip(t);
  saveTimers();
  startTick();
}

function removeTimer(t) {
  const refs = chipEls[t.id];
  timers = timers.filter((x) => x.id !== t.id);
  saveTimers();
  if (refs) {
    refs.chip.classList.add("removing");
    refs.chip.addEventListener(
      "animationend",
      () => {
        refs.chip.remove();
        delete chipEls[t.id];
      },
      { once: true },
    );
  }
  stopTickIfIdle();
}

function startTick() {
  if (tickHandle) return;
  if (!timers.some((t) => t.running)) return;
  tickHandle = setInterval(tick, 200);
}

function stopTickIfIdle() {
  if (!timers.some((t) => t.running) && tickHandle) {
    clearInterval(tickHandle);
    tickHandle = null;
  }
}

function tick() {
  let changed = false;
  timers.forEach((t) => {
    if (t.type === "timer" && t.running && !t.done) {
      const remaining = t.durationMs - elapsedOf(t);
      if (remaining <= 0) {
        t.running = false;
        t.done = true;
        t.accumMs = t.durationMs;
        t.startedAt = null;
        if (!t.chimed) {
          ensureAudio();
          playChime();
          t.chimed = true;
        }
        changed = true;
      }
    }
    if (t.type === "pomodoro" && t.running && !t.done) {
      const remaining = t.durationMs - elapsedOf(t);
      if (remaining <= 0) {
        if (!t.chimed) {
          ensureAudio();
          playChime();
          t.chimed = true;
        }
        if (t.phase === "work") {
          t.phase = "break";
          t.durationMs = t.breakMs;
        } else {
          t.phase = "work";
          t.cycle++;
          t.durationMs = t.workMs;
        }
        t.accumMs = 0;
        t.startedAt = Date.now();
        t.chimed = false;
        changed = true;
      }
    }
    updateChip(t);
  });
  if (changed) saveTimers();
  stopTickIfIdle();
}

