function parseDuration(str) {
  if (!str) return null;
  str = str.trim().toLowerCase();
  if (str.includes(":")) {
    const parts = str.split(":").map((p) => parseInt(p, 10));
    if (parts.some((n) => isNaN(n))) return null;
    let h = 0,
      m = 0,
      s = 0;
    if (parts.length === 2) {
      m = parts[0];
      s = parts[1];
    } else if (parts.length === 3) {
      h = parts[0];
      m = parts[1];
      s = parts[2];
    } else {
      return null;
    }
    return (h * 3600 + m * 60 + s) * 1000;
  }
  const match = str.match(/^(\d+(?:\.\d+)?)\s*([a-z]*)$/);
  if (!match) return null;
  const val = parseFloat(match[1]);
  if (isNaN(val)) return null;
  const unit = match[2];
  if (
    unit === "" ||
    unit === "m" ||
    unit === "min" ||
    unit === "mins" ||
    unit === "minute" ||
    unit === "minutes"
  )
    return val * 60 * 1000;
  if (
    unit === "s" ||
    unit === "sec" ||
    unit === "secs" ||
    unit === "second" ||
    unit === "seconds"
  )
    return val * 1000;
  if (
    unit === "h" ||
    unit === "hr" ||
    unit === "hrs" ||
    unit === "hour" ||
    unit === "hours"
  )
    return val * 3600 * 1000;
  return null;
}

